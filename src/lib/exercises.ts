export function findExerciseDetail(name: string): ExerciseDetail | null {
  const normalized = name.trim();

  // 完全一致
  const exact = exercises.find(
    (e) => e.name === normalized || e.aliases.includes(normalized)
  );
  if (exact) return exact;

  // 部分一致：DB名が生成名に含まれる（長い名前優先）
  const partial = exercises
    .filter((e) => normalized.includes(e.name) || e.aliases.some((a) => normalized.includes(a)))
    .sort((a, b) => b.name.length - a.name.length);
  if (partial.length > 0) return partial[0];

  // 部分一致：生成名がDB名に含まれる
  const reverse = exercises.find(
    (e) => e.name.includes(normalized) || e.aliases.some((a) => a.includes(normalized))
  );
  if (reverse) return reverse;

  return null;
}
